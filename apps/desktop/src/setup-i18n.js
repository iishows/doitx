  function candidateLocale(raw) {
    if (!raw) return "en";
    const normalized = raw.trim().toLowerCase().replace(/_/g, "-");
    if (normalized === "pt" || normalized.startsWith("pt-")) return "pt-BR";
    if (normalized === "es" || normalized.startsWith("es-")) return "es";
    if (normalized === "iw" || normalized.startsWith("iw-")) return "he";
    const [language, scriptOrRegion] = normalized.split("-");
    if (
      language === "zh" &&
      (scriptOrRegion === "hant" ||
        scriptOrRegion === "tw" ||
        scriptOrRegion === "hk" ||
        scriptOrRegion === "mo")
    ) {
      return "zh-TW";
    }
    if (language === "zh") return "zh-CN";
    return normalized.split("-")[0] ?? "";
  }

  function matchLocale(raw) {
    const candidate = candidateLocale(raw);
    return LOCALES.includes(candidate) ? candidate : "en";
  }

  window.rakazoSetupI18n = { LOCALES, LABELS, MESSAGES, RTL_LOCALES, matchLocale };
